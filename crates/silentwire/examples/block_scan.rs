use silentwire::{BlockPaymentMatch, ScanContext, ScanTransaction};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let scan_privkey = [
        0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
        0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e,
        0x1f, 0x20,
    ];

    let spend_pubkey = [
        0x02, 0x79, 0xbe, 0x66, 0x7e, 0xf9, 0xdc, 0xbb, 0xac, 0x55, 0xa0, 0x62, 0x95, 0xce, 0x87,
        0x0b, 0x07, 0x02, 0x9b, 0xfc, 0xdb, 0x2d, 0xce, 0x28, 0xd9, 0x59, 0xf2, 0x81, 0x5b, 0x16,
        0xf8, 0x17, 0x98,
    ];

    let tweak_a = [
        0x02, 0x79, 0xbe, 0x66, 0x7e, 0xf9, 0xdc, 0xbb, 0xac, 0x55, 0xa0, 0x62, 0x95, 0xce, 0x87,
        0x0b, 0x07, 0x02, 0x9b, 0xfc, 0xdb, 0x2d, 0xce, 0x28, 0xd9, 0x59, 0xf2, 0x81, 0x5b, 0x16,
        0xf8, 0x17, 0x98,
    ];

    let tweak_b = [
        0x02, 0xc6, 0x04, 0x7f, 0x94, 0x41, 0xed, 0x7d, 0x6d, 0x30, 0x45, 0x40, 0x6e, 0x95, 0xc0,
        0x7c, 0xd8, 0x5c, 0x77, 0x8e, 0x4b, 0x8c, 0xef, 0x3c, 0xa7, 0xab, 0xac, 0x09, 0xb9, 0x5c,
        0x70, 0x9e, 0xe5,
    ];

    let outputs_tx1 = [[0x11; 32], [0x22; 32]];
    let outputs_tx2 = [[0x33; 32], [0x44; 32], [0x55; 32]];

    let transactions = [
        ScanTransaction {
            tweak_point: &tweak_a,
            outputs: &outputs_tx1,
        },
        ScanTransaction {
            tweak_point: &tweak_b,
            outputs: &outputs_tx2,
        },
    ];

    let mut scanner = ScanContext::new();

    let matches = scanner.scan_block(&scan_privkey, &spend_pubkey, &transactions)?;
    assert!(matches.is_empty());

    let mut match_buf = [BlockPaymentMatch::default(); 8];
    let matched_count =
        scanner.scan_block_into(&scan_privkey, &spend_pubkey, &transactions, &mut match_buf)?;
    assert_eq!(matched_count, 0);

    Ok(())
}
