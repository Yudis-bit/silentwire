use silentwire::EmbeddedStaticScanner;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let scan_privkey = [
        0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
        0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e,
        0x1f, 0x20,
    ];

    let spend_pubkey = [
        0x02, 0x79, 0xbe, 0x66, 0x7e, 0xf9, 0xdc, 0xbb, 0xac, 0x55, 0xa0, 0x62, 0x95, 0xce, 0x87,
        0x0b, 0x07, 0x02, 0x9b, 0xfc, 0xdb, 0x2d, 0xce, 0x28, 0xd9, 0x59, 0xf2, 0x81, 0x5b, 0x16,
        0xf8, 0x17, 0x98,
    ];

    type SignerScanner = EmbeddedStaticScanner<16, 64, 8>;
    assert!(SignerScanner::memory_footprint() <= 16384);

    let mut scanner = SignerScanner::new(scan_privkey, spend_pubkey)?;

    let tweak = [
        0x02, 0x79, 0xbe, 0x66, 0x7e, 0xf9, 0xdc, 0xbb, 0xac, 0x55, 0xa0, 0x62, 0x95, 0xce, 0x87,
        0x0b, 0x07, 0x02, 0x9b, 0xfc, 0xdb, 0x2d, 0xce, 0x28, 0xd9, 0x59, 0xf2, 0x81, 0x5b, 0x16,
        0xf8, 0x17, 0x98,
    ];
    scanner.add_tweak(&tweak)?;
    scanner.add_output(&[0x11; 32])?;
    scanner.add_output(&[0x22; 32])?;

    let matches = scanner.scan()?;
    assert!(matches.is_empty());

    scanner.clear();

    Ok(())
}
