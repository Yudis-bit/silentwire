#!/usr/bin/env python3
"""Generate the signed radix-64 (32-entry) word-level comb table using independent Python arithmetic."""
from pathlib import Path
import hashlib
import json

P = 2**256 - 2**32 - 977
G = (
    0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798,
    0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8,
)


def add(a, b):
    if a is None:
        return b
    if b is None:
        return a
    x, y = a
    u, v = b
    if x == u and (y + v) % P == 0:
        return None
    slope = (
        (3 * x * x) * pow(2 * y, -1, P) if a == b else (v - y) * pow(u - x, -1, P)
    ) % P
    z = (slope * slope - x - u) % P
    return z, (slope * (x - z) - y) % P


def to_u64_be_words(value: int) -> str:
    raw = value.to_bytes(32, "big")
    words = [int.from_bytes(raw[i : i + 8], "big") for i in range(0, 32, 8)]
    return "[" + ",".join(f"0x{w:016x}" for w in words) + "]"


repo = Path(__file__).resolve().parents[1]
rows = []
encoded_signed = []
base = G
for window in range(43):
    row = []
    point = None
    for digit in range(1, 33):
        point = add(point, base)
        assert point is not None and (point[1] ** 2 - point[0] ** 3 - 7) % P == 0
        row.append("(" + to_u64_be_words(point[0]) + "," + to_u64_be_words(point[1]) + ")")
        x_bytes, y_bytes = [v.to_bytes(32, "big") for v in point]
        encoded_signed.append("04" + x_bytes.hex() + y_bytes.hex())
    rows.append("[" + ",\n".join(row) + "]")
    for _ in range(6):
        base = add(base, base)

source = "// Generated by scripts/generate_comb.py. Verified by comb table tests.\n"
source += "#[rustfmt::skip]\n"
source += "pub(super) static POINTS: [[([u64; 4], [u64; 4]); 32]; 43] = [\n"
source += ",\n".join(rows) + "\n];\n"
(repo / "crates/silentwire/src/comb_table.rs").write_text(source)
print(
    json.dumps(
        dict(
            windows=43,
            entries_per_window=32,
            points=len(encoded_signed),
            raw_coordinate_bytes=43 * 32 * 64,
            table_sha256=hashlib.sha256(bytes.fromhex("".join(encoded_signed))).hexdigest(),
        )
    )
)
